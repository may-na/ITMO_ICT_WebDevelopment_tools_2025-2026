"""Вспомогательные функции, общие для трёх реализаций Задачи 1.

Целевое (по условию) значение N = 10**13. Однако суммирование 10**13 чисел
обычным циклом на Python физически невыполнимо за разумное время (≈десятки
часов), поэтому для замеров используется практическое N (по умолчанию 10**8) —
этого достаточно, чтобы наглядно увидеть разницу между подходами. Само N
задаётся аргументом командной строки, целевое 10**13 указано как TARGET_N.
"""

TARGET_N = 10 ** 13          # значение из условия задачи
DEFAULT_N = 100_000_000      # практическое N для замеров (10**8)


def split_ranges(n: int, parts: int) -> list[tuple[int, int]]:
    """Разбить диапазон [1, n] на `parts` примерно равных отрезков.

    Возвращает список пар (start, end), границы включительны, отрезки не
    пересекаются и в сумме покрывают весь диапазон 1..n.
    """
    parts = max(1, parts)
    chunk = n // parts
    ranges: list[tuple[int, int]] = []
    start = 1
    for i in range(parts):
        end = n if i == parts - 1 else start + chunk - 1
        ranges.append((start, end))
        start = end + 1
    return ranges


def expected_sum(n: int) -> int:
    """Контрольное значение по формуле Гаусса: 1 + 2 + ... + n = n(n+1)/2."""
    return n * (n + 1) // 2
